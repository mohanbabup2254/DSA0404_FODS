# Read CSV
df = pd.read_csv(filename)

print("\nAvailable columns:")
print(list(df.columns))

# Find numeric columns
numeric_columns = df.select_dtypes(include=np.number).columns

if len(numeric_columns) == 0:
    raise ValueError("No numeric rating column was found.")

# Automatically select the first numeric column
rating_column = numeric_columns[0]

ratings = df[rating_column].dropna()

if len(ratings) < 2:
    raise ValueError("At least two valid ratings are required.")

print(f"\nRating column used: {rating_column}")
print(f"Number of ratings: {len(ratings)}")

# ------------------------------------------------------------
# User input
# ------------------------------------------------------------

confidence_level = float(
    input("\nEnter confidence level (e.g., 95 for 95%): ")
)

if not 0 < confidence_level < 100:
    raise ValueError("Confidence level must be between 0 and 100.")

# ------------------------------------------------------------
# Statistics
# ------------------------------------------------------------

n = len(ratings)
mean_rating = ratings.mean()
std_rating = ratings.std()
standard_error = std_rating / np.sqrt(n)

alpha = 1 - confidence_level / 100

# t critical value
t_critical = stats.t.ppf(
    1 - alpha / 2,
    df=n - 1
)

margin_of_error = t_critical * standard_error

lower_bound = mean_rating - margin_of_error
upper_bound = mean_rating + margin_of_error

# ------------------------------------------------------------
# Results
# ------------------------------------------------------------

print("\n" + "=" * 55)
print("CUSTOMER REVIEW ANALYSIS")
print("=" * 55)

print(f"Number of ratings       : {n}")
print(f"Mean rating             : {mean_rating:.4f}")
print(f"Standard deviation      : {std_rating:.4f}")
print(f"Standard error          : {standard_error:.4f}")
print(f"Confidence level        : {confidence_level}%")
print(f"Margin of error         : {margin_of_error:.4f}")

print(
    f"\n{confidence_level}% Confidence Interval:"
)
print(f"Lower bound             : {lower_bound:.4f}")
print(f"Upper bound             : {upper_bound:.4f}")

print(
    f"\nWe are {confidence_level}% confident that "
    f"the true population mean rating lies between "
    f"{lower_bound:.4f} and {upper_bound:.4f}."
)

print("=" * 55)

