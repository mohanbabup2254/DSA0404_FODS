import numpy as np
import matplotlib.pyplot as plt
from scipy import stats

print("=" * 60)
print("CLINICAL TRIAL HYPOTHESIS TEST")
print("=" * 60)

# ------------------------------------------------------------
# Enter data
# ------------------------------------------------------------

control_input = input(
    "\nEnter control/placebo group values separated by commas:\n"
)

treatment_input = input(
    "\nEnter treatment group values separated by commas:\n"
)

# Convert input into NumPy arrays
control = np.array(
    [float(x.strip()) for x in control_input.split(",")]
)

treatment = np.array(
    [float(x.strip()) for x in treatment_input.split(",")]
)

# Check data
if len(control) < 2 or len(treatment) < 2:
    raise ValueError(
        "Both groups must contain at least two observations."
    )

# ------------------------------------------------------------
# Calculate descriptive statistics
# ------------------------------------------------------------

control_mean = np.mean(control)
treatment_mean = np.mean(treatment)

control_std = np.std(control, ddof=1)
treatment_std = np.std(treatment, ddof=1)

# ------------------------------------------------------------
# Hypothesis test
# ------------------------------------------------------------

# H0: The treatment has no effect.
# H1: The treatment has an effect.

t_statistic, p_value = stats.ttest_ind(
    treatment,
    control,
    equal_var=False
)

alpha = 0.05

# ------------------------------------------------------------
# Results
# ------------------------------------------------------------

print("\n" + "=" * 60)
print("RESULTS")
print("=" * 60)

print(f"Control group size       : {len(control)}")
print(f"Treatment group size     : {len(treatment)}")

print(f"\nControl mean             : {control_mean:.4f}")
print(f"Treatment mean           : {treatment_mean:.4f}")

print(f"\nControl standard deviation   : {control_std:.4f}")
print(f"Treatment standard deviation : {treatment_std:.4f}")

print(f"\nT-statistic              : {t_statistic:.4f}")
print(f"P-value                  : {p_value:.6f}")
print(f"Significance level       : {alpha}")

# ------------------------------------------------------------
# Decision
# ------------------------------------------------------------

print("\n" + "-" * 60)

if p_value < alpha:
    print("Decision: REJECT the null hypothesis (H0).")
    print(
        "Conclusion: The treatment has a statistically "
        "significant effect compared with the placebo."
    )
else:
    print("Decision: FAIL TO REJECT the null hypothesis (H0).")
    print(
        "Conclusion: There is not enough statistical evidence "
        "to conclude that the treatment has a significant effect."
    )

print("=" * 60)

# ------------------------------------------------------------
# Visualization
# ------------------------------------------------------------

plt.figure(figsize=(9, 6))

plt.boxplot(
    [control, treatment],
    labels=["Control / Placebo", "Treatment"]
)

plt.ylabel("Measurement")
plt.title("Clinical Trial: Control vs Treatment")

plt.grid(axis="y", alpha=0.3)

plt.show()

# ------------------------------------------------------------
# Mean comparison graph
# ------------------------------------------------------------

plt.figure(figsize=(8, 5))

groups = ["Control / Placebo", "Treatment"]
means = [control_mean, treatment_mean]

plt.bar(groups, means)

plt.ylabel("Mean Measurement")
plt.title("Mean Comparison: Control vs Treatment")

plt.show()
