# ============================================================
# SCENARIO 21: ESTIMATION OF RARE ELEMENT CONCENTRATION
# ============================================================

import numpy as np
import pandas as pd
from google.colab import files

print("Upload the CSV file containing rare element measurements.")
uploaded = files.upload()

# Get uploaded filename
filename = list(uploaded.keys())[0]

# Read CSV
data = pd.read_csv(filename)

print("\nColumns available in the dataset:")
print(list(data.columns))

# Use the first numeric column automatically
numeric_columns = data.select_dtypes(include=np.number).columns

if len(numeric_columns) == 0:
    raise ValueError("No numeric column was found in the CSV file.")

column = numeric_columns[0]
measurements = data[column].dropna().to_numpy()

print(f"\nUsing measurement column: {column}")
print(f"Total valid measurements: {len(measurements)}")

# ------------------------------------------------------------
# User inputs
# ------------------------------------------------------------

sample_size = int(input("\nEnter sample size: "))
confidence_level = float(input("Enter confidence level (e.g., 95 for 95%): "))
precision = float(input("Enter desired precision / maximum margin of error: "))

if sample_size <= 1:
    raise ValueError("Sample size must be greater than 1.")

if sample_size > len(measurements):
    raise ValueError("Sample size cannot exceed the number of available measurements.")

if not 0 < confidence_level < 100:
    raise ValueError("Confidence level must be between 0 and 100.")

if precision <= 0:
    raise ValueError("Precision must be greater than 0.")

# ------------------------------------------------------------
# Random sampling
# ------------------------------------------------------------

np.random.seed(42)

sample = np.random.choice(
    measurements,
    size=sample_size,
    replace=False
)

# ------------------------------------------------------------
# Calculate statistics
# ------------------------------------------------------------

sample_mean = np.mean(sample)
sample_std = np.std(sample, ddof=1)
standard_error = sample_std / np.sqrt(sample_size)

# Convert confidence level to z critical value.
# NumPy is used for the numerical calculations.
# For a normal approximation, common confidence levels are handled here.

z_values = {
    90: 1.645,
    95: 1.960,
    99: 2.576
}

if confidence_level in z_values:
    z_critical = z_values[confidence_level]
else:
    # Approximation using inverse error function
    # for arbitrary confidence levels
    from statistics import NormalDist
    z_critical = NormalDist().inv_cdf(
        1 - (1 - confidence_level / 100) / 2
    )

margin_of_error = z_critical * standard_error

lower_limit = sample_mean - margin_of_error
upper_limit = sample_mean + margin_of_error

# ------------------------------------------------------------
# Display results
# ------------------------------------------------------------

print("\n" + "=" * 55)
print("RARE ELEMENT CONCENTRATION ANALYSIS")
print("=" * 55)

print(f"Sample size             : {sample_size}")
print(f"Confidence level        : {confidence_level}%")
print(f"Sample mean             : {sample_mean:.6f}")
print(f"Sample standard deviation: {sample_std:.6f}")
print(f"Standard error          : {standard_error:.6f}")
print(f"Margin of error         : {margin_of_error:.6f}")

print(
    f"\n{confidence_level}% Confidence Interval:"
)
print(f"({lower_limit:.6f}, {upper_limit:.6f})")

print(f"\nDesired precision       : ±{precision:.6f}")

if margin_of_error <= precision:
    print("Result: REQUIRED PRECISION ACHIEVED")
else:
    print("Result: REQUIRED PRECISION NOT ACHIEVED")
    print("Consider increasing the sample size.")

print("=" * 55)

